"""Generate sippo/workflow_rollout.py by verbatim extraction from the JADE ray_trainer (no hand-copying)."""
import ast, builtins, sys, hashlib
SRC="/home/hejingyu/projects/JADE/verl/trainer/ppo/ray_trainer.py"
OUT="/home/hejingyu/projects/SIPPO-npu-20261107/sippo/workflow_rollout.py"
raw=open(SRC,"rb").read().decode().replace("\r\n","\n")
lines=raw.split("\n"); t=ast.parse(raw)
METHODS=["async_rollout_batch","async_rollout_single","async_inference","assign_rewards","_get_gen_batch",
         "_is_linear_single_policy_mode","_linear_single_policy_rollout_batch","_score_node_reward_specs","_validate_planner_ccw_config",
         "_apply_planner_outcome_contrast","_planner_ccw_mode","test_validate","async_test"]
cls=[n for n in t.body if isinstance(n,ast.ClassDef) and n.name=="RayPPOTrainer"][0]
meth={m.name:m for m in cls.body if isinstance(m,(ast.FunctionDef,ast.AsyncFunctionDef))}
def seg(n):
    start=n.lineno-1
    if getattr(n,"decorator_list",None): start=min(d.lineno for d in n.decorator_list)-1
    return "\n".join(lines[start:n.end_lineno])
# module level symbols
defs={n.name:n for n in t.body if isinstance(n,(ast.FunctionDef,ast.ClassDef))}
consts={}
for n in t.body:
    if isinstance(n,ast.Assign):
        for tg in n.targets:
            if isinstance(tg,ast.Name): consts[tg.id]=n
imports={}   # bound name -> (module or None, original name, asname)
for n in t.body:
    if isinstance(n,ast.Import):
        for a in n.names: imports[(a.asname or a.name).split(".")[0]]=("import",a.name,a.asname)
    elif isinstance(n,ast.ImportFrom):
        for a in n.names: imports[a.asname or a.name]=("from",("."*n.level)+(n.module or ""),a.name,a.asname)
# names loaded inside the wanted methods (transitively through module-level helpers)
need_defs=set(); need_consts=set(); need_imports=set(); todo=list(METHODS); seen=set()
def loads(node): return {x.id for x in ast.walk(node) if isinstance(x,ast.Name) and isinstance(x.ctx,ast.Load)}
frontier=[meth[m] for m in METHODS]
while frontier:
    node=frontier.pop()
    for nm in loads(node):
        if hasattr(builtins,nm): continue
        if nm in defs and nm not in need_defs and nm!="RayPPOTrainer":
            need_defs.add(nm); frontier.append(defs[nm])
        elif nm in consts: need_consts.add(nm)
        elif nm in imports: need_imports.add(nm)
for c in list(need_consts):
    for nm in loads(consts[c]):
        if nm in imports: need_imports.add(nm)
out=["# GENERATED by generate_workflow_rollout.py -- verbatim extraction from JADE verl/trainer/ppo/ray_trainer.py",
     f"# source sha256: {hashlib.sha256(raw.encode()).hexdigest()}",
     "# Do not edit by hand; regenerate. Methods below form the mixin that the SIPPO trainer inherits.",
     "from __future__ import annotations",""]
plain=sorted(n for n in need_imports if imports[n][0]=="import")
for n in plain:
    _,mod,alias=imports[n]; out.append(f"import {mod}" + (f" as {alias}" if alias else ""))
bymod={}
for n in sorted(need_imports):
    if imports[n][0]=="from":
        _,mod,orig,alias=imports[n]; bymod.setdefault(mod,[]).append(orig+(f" as {alias}" if alias else ""))
for mod,names in sorted(bymod.items()): out.append(f"from {mod} import "+", ".join(sorted(set(names))))
out.append("")
out.append("logger = logging.getLogger(__file__)" if "logging" in need_imports else "")
for c in sorted(need_consts, key=lambda k:consts[k].lineno): out.append(seg(consts[c]))
out.append("")
for d in sorted(need_defs, key=lambda k:defs[k].lineno): out.append(seg(defs[d])); out.append("")
out.append("class WorkflowRolloutMixin:")
out.append('    """Workflow (multi-agent DAG) rollout, reward assignment and single-step inference, taken verbatim from JADE."""')
out.append("")
for m in METHODS: out.append(seg(meth[m])); out.append("")
text="\n".join(out)+"\n"
# logging-only deviation from JADE: the original swallows the exception text (often empty); also print type and traceback
old_log='logging.error(f"Error in item {item_id}, workflow sample {sample_id}: {e}")'
assert text.count(old_log)==1
text=text.replace(old_log,'logging.error(f"Error in item {item_id}, workflow sample {sample_id}: {e!r}", exc_info=True)  # SIPPO: logging only')
open(OUT,"w").write(text)
print("wrote",OUT,"| consts",sorted(need_consts),"| helper defs",len(need_defs),"| imports",len(need_imports),"| methods",len(METHODS))
print("lines:",sum(1 for _ in open(OUT)))